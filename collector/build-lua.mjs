// Generates the addon's Data.lua from the last N daily aggregates. Each item
// is stored as a comma-separated string of daily medians in copper (empty for
// days without listings), which the addon parses on first use.
//
// Also adds a region-wide house "all": per day, the median across houses.
import { appendFileSync, existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { gunzipSync } from 'node:zlib';
import { median } from './lib/stats.mjs';

const { values: args } = parseArgs({
  options: {
    region: { type: 'string', default: 'eu' },
    data: { type: 'string', default: 'data' },
    days: { type: 'string', default: '30' },
    out: { type: 'string', default: 'addon/ForeverAHHistory/Data.lua' },
  },
});

const dir = join(args.data, 'daily', args.region);
const available = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.json.gz')).sort() : [];
if (available.length === 0) {
  console.log(`No daily aggregates in ${dir}. Nothing to build.`);
  process.exit(0);
}

const latest = available.at(-1).slice(0, 10);
const numDays = Number(args.days);
const dates = Array.from({ length: numDays }, (_, i) => addDays(latest, i - numDays + 1));

const houses = new Map();
const getHouse = (key, name) => {
  if (!houses.has(key)) houses.set(key, { name, items: new Map() });
  const house = houses.get(key);
  house.name = name;
  return house;
};
const setValue = (house, itemId, dayIndex, value) => {
  if (!house.items.has(itemId)) house.items.set(itemId, new Array(numDays).fill(null));
  house.items.get(itemId)[dayIndex] = value;
};

dates.forEach((date, dayIndex) => {
  const file = join(dir, `${date}.json.gz`);
  if (!existsSync(file)) return;
  const day = JSON.parse(gunzipSync(readFileSync(file)));
  const regionWide = new Map();
  for (const [houseId, src] of Object.entries(day.houses)) {
    const house = getHouse(Number(houseId), src.name);
    for (const [itemId, [, med]] of Object.entries(src.items)) {
      setValue(house, Number(itemId), dayIndex, med);
      if (!regionWide.has(itemId)) regionWide.set(itemId, []);
      regionWide.get(itemId).push(med);
    }
  }
  const all = getHouse('all', `All houses (${args.region.toUpperCase()})`);
  for (const [itemId, meds] of regionWide) setValue(all, Number(itemId), dayIndex, median(meds));
});

const lines = [
  '-- Generated by collector/build-lua.mjs. Do not edit.',
  'ForeverAHHistory_Data = {',
  `  region = ${luaString(args.region)},`,
  `  generated = ${Math.floor(Date.now() / 1000)},`,
  `  days = { ${dates.map(luaString).join(', ')} },`,
  '  houses = {},',
  '}',
  'local H = ForeverAHHistory_Data.houses',
];
// One function per house keeps each function's constant table small.
for (const [key, house] of houses) {
  const luaKey = typeof key === 'number' ? key : luaString(key);
  lines.push(`do local function load() H[${luaKey}] = { name = ${luaString(house.name)}, items = {`);
  for (const [itemId, values] of [...house.items].sort((a, b) => a[0] - b[0])) {
    lines.push(`[${itemId}]="${values.map((v) => v ?? '').join(',')}",`);
  }
  lines.push('} } end load() end');
}
writeFileSync(args.out, `${lines.join('\n')}\n`);
console.log(`Wrote ${args.out}: ${houses.size} houses, ${dates[0]} to ${latest}`);

if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `latest=${latest}\n`);

function addDays(isoDate, delta) {
  const d = new Date(`${isoDate}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + delta);
  return d.toISOString().slice(0, 10);
}

function luaString(s) {
  return `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, '\\n')}"`;
}
